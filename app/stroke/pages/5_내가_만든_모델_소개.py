# pages/5_내가_만든_모델_소개.py — 오늘까지 만든 모델을 한 장으로 소개하는 서식
import pandas as pd
import streamlit as st

st.set_page_config(page_title="내가 만든 모델 소개", page_icon="📝", layout="wide")
st.title("📝 내가 만든 모델 소개 한 장")
st.write("앞 페이지에서 본 값과 내가 내린 판단을 여기에 적습니다. 적은 내용은 저장되지 않으므로, "
         "다 적은 뒤 화면을 갈무리하거나 활동지에 옮겨 적어 제출합니다.")

서식, 한장 = st.tabs(["① 채워 넣기", "② 한 장으로 보기"])

기본값 = {
    "무슨 데이터입니까":
        "캐글에 올라온 뇌졸중 예측 데이터입니다. 5,110명의 건강 기록이며, 뇌졸중을 겪었는지 "
        "아닌지 알아맞히는 것이 목표입니다. 게시자가 원자료 출처를 밝히지 않았고 교육 목적으로만 "
        "쓰라고 적어 두었으므로, 여기서 얻은 결과를 실제 의학적 판단에 쓰지 않습니다.",
    "무엇을 보고 맞힙니까":
        "나이, 평균 혈당, 고혈압, 심장병 네 가지를 입력으로 썼습니다. 성별과 거주 지역은 사람을 "
        "그 기준으로 나누면 편향이 생기므로 넣지 않았습니다.",
    "이 모델을 검진센터가 사용해도 됩니까":
        "쓸 수 없습니다. 누구를 모은 명단인지 알 수 없고, 검진을 받은 시점과 뇌졸중을 겪은 시점이 "
        "나뉘어 있지 않기 때문입니다. 오늘 배운 것은 이 모델 자체가 아니라 모델을 어디에 쓸 수 "
        "있는지 판단하는 방법입니다.",
}

빈칸 = {
    "무슨 데이터입니까": "미리 채워 두었습니다. 내가 확인한 것과 다르면 고쳐 씁니다.",
    "무엇을 보고 맞힙니까": "입력을 바꾸었다면 그대로 고쳐 씁니다.",
    "어떤 오류를 먼저 줄이려 했습니까": "우선한 평가 지표와 그렇게 정한 이유를 적습니다.",
    "내 최고 기록": "성능 높이기 페이지의 최고 기록 줄을 그대로 옮겨 적습니다.",
    "어떻게 해서 점수를 올렸습니까": "무엇을 바꾸었고, 그 결과 찾아낸 환자가 몇 명에서 몇 명으로 "
                                     "늘었는지 적습니다.",
    "이 모델을 검진센터가 사용해도 됩니까": "미리 채워 두었습니다. 생각이 다르면 고쳐 씁니다.",
    "이 모델이 못 하는 것 한 가지": "오늘 만든 모델이 답할 수 없는 것을 하나 적습니다.",
}

with 서식:
    답 = {}
    for 질문, 안내 in 빈칸.items():
        답[질문] = st.text_area(질문, value=기본값.get(질문, ""), placeholder=안내,
                                height=110 if 질문 in 기본값 else 90, key=질문)

    st.markdown("**점수** · 전처리 페이지 맨 아래 표에서 값을 옮겨 적습니다.")
    빈값 = ["", "", "", ""]
    점수표 = pd.DataFrame({
        "항목": ["정확도", "재현율", "정밀도", "F1"],
        "기본 설정 · 훈련용": list(빈값), "기본 설정 · 테스트용": list(빈값),
        "내 설정 · 훈련용": list(빈값), "내 설정 · 테스트용": list(빈값),
    })
    채운점수 = st.data_editor(점수표, width="stretch", hide_index=True,
                              disabled=["항목"], key="점수표")

with 한장:
    st.markdown("### 내가 만든 모델 소개")
    for 질문 in 빈칸:
        적은것 = st.session_state.get(질문, "").strip()
        st.markdown(f"**{질문}**")
        st.markdown(적은것 if 적은것 else "_아직 적지 않았습니다._")
    st.markdown("**점수**")
    st.table(채운점수.set_index("항목"))
    st.caption("훈련용 점수와 테스트용 점수가 크게 벌어졌다면 그 이유도 함께 적습니다. "
               "빈칸이 남아 있으면 ① 채워 넣기 칸으로 돌아가 채웁니다. 이 화면은 저장되지 않습니다.")

st.divider()
st.info("**이 흐름은 다른 데이터에도 그대로 됩니다** · 오늘까지 만든 앱은 데이터를 소개하고, 들여다보고, "
        "모델을 만들고, 채점하고, 고치고, 판단하는 여섯 단계로 이루어져 있습니다. "
        "바뀐 것은 데이터 주소와 열 이름뿐입니다.")
